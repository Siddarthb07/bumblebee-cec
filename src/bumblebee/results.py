from __future__ import annotations

import json
from pathlib import Path
from typing import Dict, List

from bumblebee.baselines import BM25Index, EmbedIndex, retrieval_ask
from bumblebee.data import load_evals, load_passages
from bumblebee.eval_protocol import summarize_ask_results, train_eval_split
from bumblebee.tokenize import tokenize


def _corpus_tokens(passages) -> set:
    stop = {
        "a", "an", "the", "and", "or", "of", "to", "in", "on", "for", "is", "are",
        "what", "which", "who", "how", "why", "when", "where",
    }
    return {t for p in passages for t in tokenize(p.text) if t not in stop and len(t) > 2}


def bench_all(root: Path, include_tiny: bool = False) -> dict:
    """CEC vs retrieval baselines with shared refuse family (threshold + faithfulness + lexical OOD)."""
    del include_tiny  # tiny TransformerEncoder baseline removed
    passages = load_passages(root / "data" / "corpus")
    evals = load_evals(root / "data" / "evals" / "questions.jsonl")
    _, test_evals = train_eval_split(evals)
    pairs = [(p.id, p.text) for p in passages]
    corpus_toks = _corpus_tokens(passages)
    report: Dict[str, dict] = {}

    for name, index, thr in (
        ("bm25", BM25Index(pairs), 0.45),
        ("embed", EmbedIndex(pairs), 0.55),
        # Same thresholds without lexical OOD — shows the protocol gap
        ("bm25_raw", BM25Index(pairs), 0.45),
        ("embed_raw", EmbedIndex(pairs), 0.55),
    ):
        use_lex = not name.endswith("_raw")

        def make_ask(index=index, thr=thr, use_lex=use_lex):
            def _ask(ex):
                return retrieval_ask(
                    index,
                    ex.question,
                    thr,
                    faithfulness=True,
                    lexical_ood=use_lex,
                    corpus_tokens=corpus_toks if use_lex else None,
                )

            return _ask

        pairs_out = ((ex, make_ask()(ex)) for ex in test_evals)
        report[name] = summarize_ask_results(pairs_out)
        report[name]["threshold"] = thr
        report[name]["n"] = len(test_evals)
        report[name]["refuse_protocol"] = (
            "threshold+faithfulness+lexical_ood" if use_lex else "threshold+faithfulness"
        )

    cec_path = root / "artifacts" / "eval_report.json"
    if cec_path.exists():
        report["cec"] = json.loads(cec_path.read_text(encoding="utf-8"))

    out = root / "artifacts" / "bench_all.json"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(json.dumps(report, indent=2), encoding="utf-8")
    _write_results_md(root, report)
    return report


def _write_results_md(root: Path, report: dict) -> Path:
    lines = [
        "# Results",
        "",
        "Generated by `python -m bumblebee.cli bench --mode all`.",
        "",
        "Protocol: **disjoint** holdout; **BM25 retrieve then score** (no gold passage gift to CEC).",
        "Baselines `bm25` / `embed` use the **same refuse family** (threshold + faithfulness + lexical OOD).",
        "`*_raw` rows keep threshold+faithfulness only (legacy comparison).",
        "Predictions never use gold answers. Extractive-first decode. Lower AURC is better.",
        "`ece_answered` = calibration on answered subset only; `ece`/`ece_mixed` is legacy/diagnostic.",
        "",
        "| System | In-domain F1 | F1 n | F1 CI95 | OOD refuse P | OOD refuse R | ECE answered | ECE mixed | AURC |",
        "| --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: |",
    ]
    order = ["cec", "bm25", "embed", "bm25_raw", "embed_raw"]
    for key in order:
        if key not in report:
            continue
        r = report[key]
        ci = r.get("in_domain_f1_ci95")
        ci_s = f"[{ci[1]:.3f},{ci[2]:.3f}]" if ci and len(ci) == 3 else "—"
        ece_a = r.get("ece_answered", r.get("ece", float("nan")))
        ece_m = r.get("ece_mixed", r.get("ece", float("nan")))
        try:
            ece_a_s = f"{float(ece_a):.3f}"
        except (TypeError, ValueError):
            ece_a_s = "—"
        try:
            ece_m_s = f"{float(ece_m):.3f}"
        except (TypeError, ValueError):
            ece_m_s = "—"
        lines.append(
            f"| {key} | {r.get('in_domain_f1_mean', float('nan')):.3f} | "
            f"{r.get('in_domain_f1_n', r.get('ood_refuse_tn', '—'))} | {ci_s} | "
            f"{r.get('ood_refuse_precision', float('nan')):.3f} | "
            f"{r.get('ood_refuse_recall', float('nan')):.3f} | "
            f"{ece_a_s} | {ece_m_s} | "
            f"{r.get('aurc', float('nan')):.3f} |"
        )
    if report.get("cec", {}).get("oracle_passage_f1_mean") is not None:
        lines += [
            "",
            f"Oracle-passage F1 (diagnostic only, not same-protocol): "
            f"{report['cec']['oracle_passage_f1_mean']:.3f} "
            f"(n={report['cec'].get('oracle_passage_f1_n', '?')}).",
        ]
    cfg = root / "artifacts" / "config.json"
    if cfg.exists():
        c = json.loads(cfg.read_text(encoding="utf-8"))
        n = c.get("n_params")
        dim = c.get("dim", 192)
        buckets = c.get("n_buckets", 0)
        emb_dim = c.get("emb_dim", 0)
        hash_p = int(buckets) * int(emb_dim) if buckets and emb_dim else 0
        core_est = (n or 0) - hash_p if n else 0
        lines += [
            "",
            "## Param card (honest)",
            "",
            f"- **Headline params:** {n:,}" if n else "",
            f"- **Sparse hash table:** {buckets:,} × {emb_dim} ≈ {hash_p:,} (mostly untouched rows)",
            f"- **Dense core (approx):** ~{core_est:,} at dim={dim}",
            f"- **Temperature (post-hoc):** {c.get('temperature', 1.0)}",
            f"- **Platt:** a={c.get('platt_a', '—')} b={c.get('platt_b', '—')} active={c.get('platt_active', False)}",
            f"- **Mass fn:** {c.get('mass_fn', 'sparsemax')}",
            "",
            "Do not equate sparse hash params with dense transformer FLOPs.",
        ]
        lines = [x for x in lines if x is not None]
    cec = report.get("cec") or {}
    if cec.get("by_split"):
        lines += ["", "## CEC refuse by split (held-out OOD)", ""]
        lines += ["| Split | N | Refuse P | Refuse R |", "| --- | ---: | ---: | ---: |"]
        for sk, s in sorted(cec["by_split"].items()):
            if sk == "in_domain":
                continue
            lines.append(
                f"| {sk} | {s.get('n', 0)} | {s.get('ood_refuse_precision', 0):.3f} | "
                f"{s.get('ood_refuse_recall', 0):.3f} |"
            )
    src = root / "data" / "hf_source.json"
    if src.exists():
        meta = json.loads(src.read_text(encoding="utf-8"))
        lines.extend(
            [
                "",
                "## Dataset",
                "",
                f"- Hugging Face (ingest source only): `{meta.get('dataset')}`",
                f"- Closed passages: {meta.get('n_passages')}",
                f"- Eval questions: {meta.get('n_evals')} ({meta.get('splits')})",
            ]
        )
    seal = root / "data" / "sealed" / "SEAL.json"
    if seal.exists():
        s = json.loads(seal.read_text(encoding="utf-8"))
        lines.extend(
            [
                "",
                "## Sealed pack",
                "",
                f"- Seal SHA-256: `{s.get('seal_sha256', '')[:16]}…`",
                f"- Passages SHA-256: `{s.get('passages_sha256', '')[:16]}…`",
                f"- Evals SHA-256: `{s.get('evals_sha256', '')[:16]}…`",
                "- Reproducibility only — not external validity.",
            ]
        )
    lines.extend(
        [
            "",
            "## Reading",
            "",
            "- Product skills 20/20 ≠ core CEC skill — see `docs/SKILLS_BENCH.md` dual scoreboard.",
            "- If BM25 wins in-domain F1 on the **retrieved** protocol, say so.",
            "- Prefer `ece_answered` over mixed ECE (correct refuses at low conf inflate mixed ECE).",
            "- `docs/SYSTEMS_BENCH.md` is quarantined — do not cite.",
            "- Scaled CEC asset pack ≠ frontier LLM (no transformer backend).",
            "- See also `docs/MEMORY_BENCH.md`, `docs/LLM_COMPARE.md`, `docs/MODEL_ADVICE_SYNTHESIS.md`, `docs/INSANE_ROADMAP.md`.",
            "",
            "## Artifacts",
            "",
            "- `artifacts/eval_report.json` — CEC (honest holdout)",
            "- `artifacts/calibration.json` — temperature / Platt fit",
            "- `artifacts/bench_all.json` — combined selective card",
            "- `artifacts/bench_skills.json` — dual scoreboard",
            "- `artifacts/bench_adversarial.json` — paraphrase / distractor / conflict",
        "- `artifacts/ablation_mass.json` — SoftCorrelator mass_fn ablation",
        "- `artifacts/ablation_linear.json` — classic vs SSM+gated_delta scratch vs distill",
        "- `artifacts/cec_linear.pt` — optional distilled linear student (not product default)",
        "- `artifacts/bench_memory.json` — CEC RSS/params vs LLM weight catalogs",
        "- `data/sealed/SEAL.json` — pack checksums",
            "",
        ]
    )
    # Explicit win/lose line for honesty on this pack
    cec_f1 = (report.get("cec") or {}).get("in_domain_f1_mean")
    bm25_f1 = (report.get("bm25") or {}).get("in_domain_f1_mean")
    if cec_f1 is not None and bm25_f1 is not None:
        verdict = (
            f"On this pack, **BM25 leads CEC** on retrieved in-domain F1 "
            f"({bm25_f1:.3f} vs {cec_f1:.3f})."
            if bm25_f1 > cec_f1
            else f"On this pack, **CEC leads BM25** on retrieved in-domain F1 "
            f"({cec_f1:.3f} vs {bm25_f1:.3f})."
        )
        # Insert after the "If BM25 wins..." bullet
        for i, line in enumerate(lines):
            if line.startswith("- If BM25 wins"):
                lines.insert(i + 1, f"- {verdict}")
                break
    path = root / "docs" / "RESULTS.md"
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return path
